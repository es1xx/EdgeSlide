//! Independent native-gesture settings. Existing config.toml is never rewritten here.
use anyhow::{bail, Result};
use serde::{Deserialize, Serialize};
use std::path::PathBuf;
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SwipeAction {
    Disabled,
    PreviousWorkspace,
    NextWorkspace,
    Screenshot,
    Overview,
    Custom,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Swipe {
    pub enabled: bool,
    pub action: SwipeAction,
    pub sensitivity: f64,
    #[serde(default)]
    pub command: String,
}
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct MultiConfig {
    pub enabled: bool,
    pub four_left: Swipe,
    pub four_right: Swipe,
    pub three_down: Swipe,
    pub three_up: Swipe,
}
impl Default for MultiConfig {
    fn default() -> Self {
        let mapping = |action, enabled| Swipe {
            enabled,
            action,
            sensitivity: 1.0,
            command: String::new(),
        };
        Self {
            enabled: true,
            four_left: mapping(SwipeAction::PreviousWorkspace, true),
            four_right: mapping(SwipeAction::NextWorkspace, true),
            three_down: mapping(SwipeAction::Screenshot, true),
            three_up: mapping(SwipeAction::Overview, false),
        }
    }
}
impl MultiConfig {
    pub fn entries(&self) -> [(&'static str, u32, &'static str, &Swipe); 4] {
        [
            ("four_left", 4, "left", &self.four_left),
            ("four_right", 4, "right", &self.four_right),
            ("three_down", 3, "down", &self.three_down),
            ("three_up", 3, "up", &self.three_up),
        ]
    }
    pub fn validate(&self) -> Result<()> {
        for (name, _, _, mapping) in self.entries() {
            if !mapping.sensitivity.is_finite() || !(0.25..=4.0).contains(&mapping.sensitivity) {
                bail!("{name}: sensitivity must be 0.25–4");
            }
            if mapping.command.contains('\0') || mapping.command.len() > 8192 {
                bail!("{name}: invalid or oversized command");
            }
            if self.enabled
                && mapping.enabled
                && matches!(mapping.action, SwipeAction::Overview | SwipeAction::Custom)
                && mapping.command.trim().is_empty()
            {
                bail!(
                    "{name}: supply a supported overview command or custom command before enabling"
                );
            }
        }
        Ok(())
    }
    pub fn path() -> Result<PathBuf> {
        Ok(crate::config_path()?.with_file_name("gestures.toml"))
    }
    pub fn load() -> Result<Self> {
        match std::fs::read_to_string(Self::path()?) {
            Ok(text) => {
                let config: Self = toml::from_str(&text)?;
                config.validate()?;
                Ok(config)
            }
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(Self::default()),
            Err(error) => Err(error.into()),
        }
    }
    pub fn save(&self) -> Result<()> {
        use std::io::Write;
        use std::os::unix::fs::OpenOptionsExt;
        self.validate()?;
        let path = Self::path()?;
        std::fs::create_dir_all(path.parent().unwrap())?;
        let temporary = path.with_extension(format!("{}.tmp", std::process::id()));
        let mut file = std::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .mode(0o600)
            .open(&temporary)?;
        let result = (|| -> Result<()> {
            file.write_all(toml::to_string_pretty(self)?.as_bytes())?;
            file.sync_all()?;
            std::fs::rename(&temporary, &path)?;
            Ok(())
        })();
        if result.is_err() {
            let _ = std::fs::remove_file(temporary);
        }
        result
    }
    pub fn lua(&self) -> Result<String> {
        self.validate()?;
        let mut output =
            String::from("-- Generated by EdgeSlide. Only multi-finger configuration.\nreturn {\n");
        for (name, fingers, direction, mapping) in self.entries() {
            let action = match mapping.action {
                SwipeAction::Disabled => "disabled",
                SwipeAction::PreviousWorkspace => "previous",
                SwipeAction::NextWorkspace => "next",
                SwipeAction::Screenshot => "screenshot",
                SwipeAction::Overview => "overview",
                SwipeAction::Custom => "custom",
            };
            output.push_str(&format!("{{name={}, fingers={fingers}, direction={}, enabled={}, action={}, threshold={}, command={}}},\n",lua_string(name),lua_string(direction),self.enabled&&mapping.enabled&&mapping.action!=SwipeAction::Disabled,lua_string(action),80.0/mapping.sensitivity,lua_string(&mapping.command)));
        }
        output.push_str("}\n");
        Ok(output)
    }
}
pub fn lua_string(value: &str) -> String {
    let mut result = String::from("\"");
    for byte in value.bytes() {
        match byte {
            b'"' => result.push_str("\\\""),
            b'\\' => result.push_str("\\\\"),
            0..=31 | 127..=255 => result.push_str(&format!("\\{byte:03}")),
            _ => result.push(char::from(byte)),
        }
    }
    result.push('"');
    result
}
#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn defaults_and_legacy_config_are_independent() {
        let old = include_str!("../../data/config.toml");
        crate::Config::parse(old).unwrap();
        let c = MultiConfig::default();
        c.validate().unwrap();
        assert!(!c.three_up.enabled);
        assert_eq!(c.four_left.action, SwipeAction::PreviousWorkspace);
    }
    #[test]
    fn overview_requires_explicit_provider() {
        let mut c = MultiConfig::default();
        c.three_up.enabled = true;
        assert!(c.validate().is_err());
        c.three_up.command = "my-overview toggle".into();
        assert!(c.validate().is_ok());
    }
    #[test]
    fn rejects_invalid_sensitivity() {
        for v in [0.0, 5.0, f64::NAN, f64::INFINITY] {
            let mut c = MultiConfig::default();
            c.four_left.sensitivity = v;
            assert!(c.validate().is_err());
        }
    }
    #[test]
    fn generated_commands_are_data() {
        assert_eq!(lua_string("\"\n\\123"), "\"\\\"\\010\\\\123\"");
        let mut c = MultiConfig::default();
        c.four_left.action = SwipeAction::Custom;
        c.four_left.command = "\"); error('injection'); --".into();
        assert!(c.lua().unwrap().contains("\\\""));
    }
    #[test]
    fn roundtrip() {
        let c = MultiConfig::default();
        let loaded: MultiConfig = toml::from_str(&toml::to_string(&c).unwrap()).unwrap();
        assert_eq!(loaded.lua().unwrap(), c.lua().unwrap());
    }
}
